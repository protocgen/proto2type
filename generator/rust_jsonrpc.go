package generator

import (
	"fmt"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

// generateRustJsonrpc generates a Rust file with flat serde-tagged enums
// for proto messages that have exactly one oneof. This eliminates manual
// JSON-RPC bridge code by producing enums that serialize directly to the
// flat wire format expected by JSON-RPC clients.
func generateRustJsonrpc(gen *protogen.Plugin, file *protogen.File, opts *Options) error {
	filename := outputFilename(file.GeneratedFilenamePrefix, "_jsonrpc.type.rs")

	g := gen.NewGeneratedFile(filename, "")

	// Build IR from the proto file.
	df := BuildDomainFile(file, opts)

	// Header
	g.P("// Code generated by proto2type. DO NOT EDIT.")
	g.P("// proto2type v", Version)
	g.P("// source: ", file.Desc.Path())
	g.P("// backend: jsonrpc")
	g.P()

	// Collect all eligible messages (including nested) upfront so we can
	// scan them for import needs and skip file generation if empty.
	type eligibleEntry struct {
		msg    *DomainMessage
		msgMap map[string]*DomainMessage
	}
	var eligible []eligibleEntry

	// Build message lookup for resolving variant message types.
	msgMap := make(map[string]*DomainMessage)
	for _, dm := range df.Messages {
		msgMap[dm.Name] = dm
		for _, nested := range dm.NestedMessages {
			msgMap[nested.Name] = nested
		}
	}

	for _, dm := range df.Messages {
		if isJsonrpcEligible(dm) {
			eligible = append(eligible, eligibleEntry{dm, msgMap})
		}
		for _, nested := range dm.NestedMessages {
			if isJsonrpcEligible(nested) {
				eligible = append(eligible, eligibleEntry{nested, msgMap})
			}
		}
	}

	if len(eligible) == 0 {
		// Nothing to generate — don't emit an empty file.
		g.Skip()
		return nil
	}

	// Scan for needed imports.
	needsSerdeJson := false
	needsChrono := false
	for _, e := range eligible {
		jsonrpcScanImports(e.msg, msgMap, &needsSerdeJson, &needsChrono)
	}

	// Emit use statements.
	g.P("use serde::{Deserialize, Serialize};")
	if needsSerdeJson {
		g.P("use serde_json;")
	}
	if needsChrono {
		g.P("use chrono::{DateTime, Utc};")
	}
	g.P()
	g.P("use super::*;")
	g.P()

	// Generate flat enums for each eligible message.
	for _, e := range eligible {
		generateRustJsonrpcEnum(g, e.msg, msgMap, opts)
	}

	return nil
}

// isJsonrpcEligible returns true if the message has exactly one oneof
// and all non-oneof fields are simple scalars (no repeated, no maps,
// no message-typed fields). Messages that don't match are skipped —
// the domain backend handles those independently.
func isJsonrpcEligible(dm *DomainMessage) bool {
	if dm.Skip {
		return false
	}
	if len(dm.Oneofs) != 1 {
		return false
	}
	// All non-oneof fields must be simple (scalar, optional scalar, enum,
	// or well-known scalar-like types such as Timestamp/Duration).
	for _, f := range dm.Fields {
		if f.IsOneof {
			continue
		}
		if f.Repeated || f.IsMap {
			return false
		}
		if f.Kind == FieldKindMessage {
			return false
		}
	}
	return true
}

// jsonrpcScanImports scans an eligible message's hoisted and variant fields
// for types that require extra use statements.
func jsonrpcScanImports(dm *DomainMessage, msgMap map[string]*DomainMessage, needsSerdeJson, needsChrono *bool) {
	// Scan hoisted fields.
	for _, f := range dm.Fields {
		if f.IsOneof {
			continue
		}
		if f.Kind == FieldKindTimestamp {
			*needsChrono = true
		}
		if f.Kind == FieldKindStruct || f.Kind == FieldKindValue || f.Kind == FieldKindListValue || f.Kind == FieldKindAny {
			*needsSerdeJson = true
		}
	}
	// Scan variant messages' fields.
	oneof := dm.Oneofs[0]
	for _, v := range oneof.Variants {
		if v.Kind == FieldKindTimestamp {
			*needsChrono = true
		}
		if v.Kind == FieldKindStruct || v.Kind == FieldKindValue || v.Kind == FieldKindListValue {
			*needsSerdeJson = true
		}
		if v.Kind == FieldKindMessage {
			if variantMsg := msgMap[v.TypeName]; variantMsg != nil {
				for _, f := range variantMsg.Fields {
					if f.Kind == FieldKindTimestamp {
						*needsChrono = true
					}
					if f.Kind == FieldKindStruct || f.Kind == FieldKindValue ||
						f.Kind == FieldKindListValue || f.Kind == FieldKindAny {
						*needsSerdeJson = true
					}
				}
			}
		}
	}
}

// generateRustJsonrpcEnum emits a flat serde-tagged enum for a single eligible message.
func generateRustJsonrpcEnum(g *protogen.GeneratedFile, dm *DomainMessage, msgMap map[string]*DomainMessage, opts *Options) {
	oneof := dm.Oneofs[0]

	// Collect hoisted fields (non-oneof fields from the parent message).
	var hoistedFields []*DomainField
	for _, f := range dm.Fields {
		if !f.IsOneof {
			hoistedFields = append(hoistedFields, f)
		}
	}

	// Use suffix "Rpc" to avoid collision with the domain struct.
	enumName := dm.Name + "Rpc"

	// Doc comment.
	g.P("/// Flat JSON-RPC representation of ", dm.Name, ".")
	g.P("/// Generated from proto message with oneof '", oneof.FieldName, "'.")

	// Derive and serde attributes.
	g.P("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]")
	g.P(`#[serde(tag = "type", rename_all = "snake_case")]`)
	if !opts.RustExhaustive {
		g.P("#[non_exhaustive]")
	}
	g.P("pub enum ", enumName, " {")

	for _, v := range oneof.Variants {
		// Look up the variant's message in the IR to get its fields.
		variantMsg := msgMap[v.TypeName]

		g.P("    ", v.Name, " {")

		// Hoisted fields first.
		for _, f := range hoistedFields {
			emitJsonrpcField(g, f, "        ")
		}

		// Inlined fields from the variant's message.
		if variantMsg != nil {
			for _, vf := range variantMsg.Fields {
				emitJsonrpcField(g, vf, "        ")
			}
		} else if v.Kind == FieldKindScalar || v.Kind == FieldKindEnum {
			// Scalar/enum variant (not a message) — emit the value directly.
			fieldType := rustJsonrpcVariantScalarType(v)
			g.P("        value: ", fieldType, ",")
		}

		g.P("    },")
	}

	g.P("}")
	g.P()
}

// emitJsonrpcField emits a single field declaration with serde attributes.
func emitJsonrpcField(g *protogen.GeneratedFile, f *DomainField, indent string) {
	fieldType := rustJsonrpcFieldType(f)
	rustFieldName := escapeRustKeyword(toSnakeCase(f.PascalName))
	protoName := f.Name

	// Serde attributes.
	attrs := []string{}

	// Rename if the Rust field name differs from proto name.
	if f.NameOverride != "" {
		attrs = append(attrs, fmt.Sprintf(`rename = "%s"`, f.NameOverride))
	} else if rustFieldName != protoName {
		attrs = append(attrs, fmt.Sprintf(`rename = "%s"`, protoName))
	}

	// Optional fields.
	if strings.HasPrefix(fieldType, "Option<") {
		attrs = append(attrs, `default`)
		attrs = append(attrs, `skip_serializing_if = "Option::is_none"`)
	}

	// Default for collection/struct types.
	if f.Repeated || f.IsMap || f.Kind == FieldKindStruct ||
		f.Kind == FieldKindValue || f.Kind == FieldKindListValue ||
		f.Kind == FieldKindFieldMask {
		attrs = append(attrs, `default`)
	}

	if len(attrs) > 0 {
		g.P(indent, "#[serde(", strings.Join(attrs, ", "), ")]")
	}

	// Duration doc comment.
	if f.Kind == FieldKindDuration {
		g.P(indent, "/// Duration in milliseconds")
	}

	g.P(indent, rustFieldName, ": ", fieldType, ",")
}

// rustJsonrpcFieldType returns the Rust type for a field in the jsonrpc enum.
// Mostly delegates to rustDomainSingularTypeFromIR but overrides FieldKindStruct
// to use serde_json::Value (design decision: simpler for JSON-RPC payloads).
func rustJsonrpcFieldType(f *DomainField) string {
	// Handle repeated fields.
	if f.Repeated {
		return "Vec<" + rustJsonrpcElementType(f) + ">"
	}

	// Handle map fields.
	if f.IsMap {
		keyType := rustType(f.MapKey.ScalarKind)
		valType := rustMapValueTypeFromIR(f.MapValue, f.EnumAsString)
		return fmt.Sprintf("HashMap<%s, %s>", keyType, valType)
	}

	// Override: Struct → serde_json::Value (not Map<String, Value>).
	switch f.Kind {
	case FieldKindStruct:
		if f.Optional {
			return "Option<serde_json::Value>"
		}
		return "serde_json::Value"
	default:
		return rustDomainSingularTypeFromIR(f)
	}
}

// rustJsonrpcElementType returns the element type for repeated fields in jsonrpc context.
func rustJsonrpcElementType(f *DomainField) string {
	if f.Kind == FieldKindStruct {
		return "serde_json::Value"
	}
	return rustDomainListElementTypeFromIR(f)
}

// rustJsonrpcVariantScalarType returns the Rust type for a scalar/enum oneof variant value.
func rustJsonrpcVariantScalarType(v *OneofVariant) string {
	switch v.Kind {
	case FieldKindEnum:
		if v.EnumAsString {
			return "String"
		}
		return v.TypeName
	case FieldKindTimestamp:
		return "DateTime<Utc>"
	case FieldKindDuration:
		return "i64"
	case FieldKindStruct:
		return "serde_json::Value"
	case FieldKindValue:
		return "serde_json::Value"
	case FieldKindScalar:
		return rustType(v.ScalarKind)
	default:
		return rustType(v.ScalarKind)
	}
}
