// generateSearchIndexExtractor generates an Extract<Name>Indexes function
// for a proto message. When postgres_search_params is provided, it uses
// SearchParameter definitions to generate precise FHIRPath-compiled extraction.
// Otherwise, it falls back to a naive field walk as a starting point.
func generateSearchIndexExtractor(gen *protogen.Plugin, g *protogen.GeneratedFile, msg *protogen.Message, opts *Options, spIndex SearchParamIndex) error {
	msgName := msg.GoIdent.GoName
	resType := msgName // e.g. "Patient"

	// Select search params for this resource type from the loaded index
	var searchParams []SearchParam
	if spIndex != nil {
		searchParams = spIndex[resType]
	}

	g.P(fmt.Sprintf("// Extract%sIndexes extracts HAPI-style search index rows from a %s proto.", msgName, msgName))
	g.P("// Each SearchParameter expression is compiled to a direct proto field accessor.")
	g.P(fmt.Sprintf("func Extract%sIndexes(tenantID string, r *%s) *SearchIndexes {", msgName, g.QualifiedGoIdent(msg.GoIdent)))
	g.P("	if r == nil {")
	g.P("		return &SearchIndexes{}")
	g.P("	}")
	g.P()
	g.P("	idx := &SearchIndexes{}")
	g.P("	resID := \"\"")
	g.P("	_ = resID")
	g.P()

	// Find the ID field — google/fhir wraps it in a message
	for _, field := range msg.Fields {
		if strings.ToLower(string(field.Desc.Name())) == "id" {
			g.P("	// Extract resource ID")
			g.P(fmt.Sprintf("	if r.Get%s() != nil {", field.GoName))

			// Check if the field is a message (wrapped primitive like Id{Value: "..."})
			if field.Desc.Kind().String() == "message" {
				g.P(fmt.Sprintf("		resID = r.Get%s().GetValue()", field.GoName))
			} else {
				g.P(fmt.Sprintf("		resID = r.Get%s()", field.GoName))
			}

			g.P("	}")
			g.P()
			break
		}
	}

	// Use SearchParameter-driven extraction if search params are loaded
	if len(searchParams) > 0 {
		if err := emitSearchIndexExtraction(g, msg, searchParams, resType); err != nil {
			return err
		}
	} else if spIndex == nil {
		// Fallback: naive field walk for wrapped string fields (no search params JSON provided)
		for _, field := range msg.Fields {
			fieldName := string(field.Desc.Name())
			goGetter := fmt.Sprintf("Get%s()", field.GoName)

			if isWrappedStringField(field) {
				spName := toSearchParamName(fieldName)
				if field.Desc.IsList() {
					g.P(fmt.Sprintf("	// SearchParameter: %s (%s)", spName, resType+"."+fieldName))
					g.P(fmt.Sprintf("	for _, v := range r.%s {", goGetter))
					g.P("		if v != nil && v.GetValue() != \"\" {")
					g.P("			idx.Strings = append(idx.Strings, SpidxString{")
					g.P("				TenantID: tenantID,")
					g.P(fmt.Sprintf("				ResType:  %q,", resType))
					g.P("				ResID:    resID,")
					g.P(fmt.Sprintf("				SpName:   %q,", spName))
					g.P("				SpValue:  strings.ToLower(v.GetValue()),")
					g.P("			})")
					g.P("		}")
					g.P("	}")
					g.P()
				} else {
					g.P(fmt.Sprintf("	// SearchParameter: %s (%s)", spName, resType+"."+fieldName))
					g.P(fmt.Sprintf("	if r.%s != nil && r.%s.GetValue() != \"\" {", goGetter, goGetter))
					g.P("		idx.Strings = append(idx.Strings, SpidxString{")
					g.P("			TenantID: tenantID,")
					g.P(fmt.Sprintf("			ResType:  %q,", resType))
					g.P("			ResID:    resID,")
					g.P(fmt.Sprintf("			SpName:   %q,", spName))
					g.P(fmt.Sprintf("			SpValue:  strings.ToLower(r.%s.GetValue()),", goGetter))
					g.P("		})")
					g.P("	}")
					g.P()
				}
			}
		}
	}

	g.P("	return idx")
	g.P("}")
	g.P()

	return nil
}

// isWrappedStringField returns true if the field is a google/fhir wrapped string
// (a message with a "value" field of type string).
func isWrappedStringField(field *protogen.Field) bool {
	if field.Desc.Kind().String() != "message" {
		return false
	}
	if field.Message == nil {
		return false
	}
	// Check if the message has a "value" field of type string
	for _, f := range field.Message.Fields {
		if string(f.Desc.Name()) == "value" && f.Desc.Kind().String() == "string" {
			return true
		}
	}
	return false
}

// toSearchParamName converts a proto field name to a FHIR SearchParameter name.
// e.g. "birth_date" -> "birthdate", "managing_organization" -> "organization"
func toSearchParamName(protoName string) string {
	// Remove underscores and lowercase (simplified — full mapping from search-parameters.json)
	return strings.ReplaceAll(strings.ToLower(protoName), "_", "")
}
