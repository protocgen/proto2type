// generateGoPostgresSearchIndex generates HAPI-style search index extraction
// functions for FHIR resources. Given a proto message (e.g. Patient), it
// produces an Extract<Name>Indexes() function that walks the proto fields
// and emits rows for the 8 spidx_* tables (token, string, date, quantity,
// reference, uri, present, number).
//
// This mode is activated via:
//
//	opt:
//	  - backend=postgres
//	  - postgres_mode=search_index
//	  - postgres_search_params=fhir/r4/search-parameters.json
func (gg *goGenerator) generateGoPostgresSearchIndex(gen *protogen.Plugin, file *protogen.File, opts *Options) error {
	filename, err := outputFilename(file.GeneratedFilenamePrefix, "_search_index.go")
	if err != nil {
		return err
	}

	goImportPath := file.GoImportPath
	goPackageName := file.GoPackageName
	if opts.GoPackage != "" {
		importPath, pkgName := parseGoPackage(opts.GoPackage)
		goImportPath = protogen.GoImportPath(importPath)
		goPackageName = protogen.GoPackageName(pkgName)
		filename = filepath.Base(filename)
	}
	g := gen.NewGeneratedFile(filename, goImportPath)

	// Header
	g.P("// Code generated by proto2type. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P("// backend: postgres")
	g.P("// mode: search_index")
	g.P()
	g.P("package ", goPackageName)
	g.P()
	g.P(`import (`)
	g.P(`	"fmt"`)
	g.P(`	"strings"`)
	g.P(`	"time"`)
	g.P(``)
	g.P(`	proto "google.golang.org/protobuf/proto"`)
	g.P(`)`)
	g.P()

	// Generate the search index row types (shared across all resources in the same Go package)
	if !gg.emittedSearchIndexTypes[goImportPath] {
		gg.emittedSearchIndexTypes[goImportPath] = true
		generateSearchIndexTypes(g)
	}

	// Suppress unused import warnings in this file
	g.P("var (")
	g.P("	_ = strings.ToLower")
	g.P("	_ = time.Now")
	g.P("	_ = proto.Marshal")
	g.P("	_ = fmt.Sprintf")
	g.P(")")
	g.P()

	// Load search params once if configured
	var spIndex SearchParamIndex
	if opts.PostgresSearchParams != "" {
		var err error
		spIndex, err = LoadSearchParams(opts.PostgresSearchParams)
		if err != nil {
			return fmt.Errorf("loading search params: %w", err)
		}
	}

	// Generate extraction functions for each top-level message
	for _, msg := range file.Messages {
		if err := generateSearchIndexExtractor(gen, g, msg, opts, spIndex); err != nil {
			return err
		}
	}

	return nil
}

