// generateTypeScript generates TypeScript/Zod output for a proto file.
func generateTypeScript(gen *protogen.Plugin, file *protogen.File, opts *Options) error {
	if opts.Backend != "" {
		return fmt.Errorf("proto2type: TypeScript does not support backend %q", opts.Backend)
	}
	if opts.TSTypesOnly && opts.ValidateEnabled() {
		return fmt.Errorf("proto2type: validate=%q requires Zod runtime; cannot be used with ts_types_only=true", opts.Validate)
	}
	if !opts.Domain {
		return nil
	}
	return generateTypeScriptDomain(gen, file, opts)
}

// generateTypeScriptDomain generates TypeScript/Zod output for a proto file.
func generateTypeScriptDomain(gen *protogen.Plugin, file *protogen.File, opts *Options) error {
	ir, err := BuildDomainFile(file, opts)
	if err != nil {
		return err
	}
	if opts.Debug {
		irJSON, err := json.MarshalIndent(ir, "", "  ")
		if err == nil {
			_, _ = fmt.Fprintf(os.Stderr, "--- proto2type IR for %s ---\n%s\n", file.Desc.Path(), irJSON)
		}
	}
	ir.Messages = flattenMessages(ir.Messages)
	ir.Messages = topologicalSortMessages(ir.Messages)

	outFile, err := tsOutputFilename(file.Desc.Path(), opts)
	if err != nil {
		return err
	}
	g := gen.NewGeneratedFile(outFile, "")

	writeTSFile(g, ir, opts)
	return nil
}

func writeTSFile(g *protogen.GeneratedFile, ir *DomainFile, opts *Options) {
	g.P("// Code generated by proto2type. DO NOT EDIT.")
	g.P("// source: ", ir.SourcePath)
	g.P("/* eslint-disable @typescript-eslint/no-explicit-any, @typescript-eslint/no-empty-interface */")

	if !opts.TSTypesOnly {
		hasRegex := irHasRegexConstraint(ir)

		if opts.TSInt64Style == "bigint" {
			g.P("// ⚠️  NOTE: BigInt values cannot be serialized with JSON.stringify() without a custom replacer.")
			g.P("// See: https://developer.mozilla.org/en-US/docs/Web/JavaScript/Reference/Global_Objects/BigInt#use_within_json")
		}
		if hasRegex {
			g.P("// ⚠️  SECURITY: Regex patterns from buf.validate are designed for RE2 (non-backtracking).")
			g.P("// This generated code uses JavaScript's RegExp (backtracking). Review patterns for ReDoS.")
		}

		zodImport := "zod"
		if opts.TSZodImport != "" {
			zodImport = opts.TSZodImport
		}
		g.P(fmt.Sprintf(`import { z } from %s;`, strconv.Quote(zodImport)))
	}

	// Cross-file imports: collect external type references and emit ESM imports.
	imports := collectTSImports(ir, opts)
	for _, imp := range imports {
		if opts.TSTypesOnly {
			g.P(fmt.Sprintf(`import type { %s } from %s;`, strings.Join(imp.names, ", "), strconv.Quote(imp.path)))
		} else {
			g.P(fmt.Sprintf(`import { %s } from %s;`, strings.Join(imp.names, ", "), strconv.Quote(imp.path)))
		}
	}
	g.P()

	// Enums.
	for _, e := range ir.Enums {
		writeTSEnum(g, e, opts)
		g.P()
	}

	// Messages (flattened and topologically sorted; nested enums emitted inline).
	for _, m := range ir.Messages {
		if m.Skip {
			continue
		}
		// Write nested enums before the message itself.
		for _, ne := range m.NestedEnums {
			writeTSEnum(g, ne, opts)
			g.P()
		}
		writeTSMessage(g, m, opts)
		g.P()
	}
}

// irHasRegexConstraint returns true if any field or oneof variant in the IR
// has a buf.validate pattern constraint (which generates a JS RegExp).
func irHasRegexConstraint(ir *DomainFile) bool {
	for _, m := range ir.Messages {
		for _, f := range m.Fields {
			if f.ValidateConstraints != nil && f.ValidateConstraints.Pattern != "" {
				return true
			}
		}
		for _, o := range m.Oneofs {
			for _, v := range o.Variants {
				if v.ValidateConstraints != nil && v.ValidateConstraints.Pattern != "" {
					return true
				}
			}
		}
	}
	return false
}

// isRecursive returns true when any field in the message requires boxing,
// indicating a recursive type cycle.
func isRecursive(m *DomainMessage) bool {
	for _, f := range m.Fields {
		if f.NeedsBox {
			return true
		}
	}
	for _, o := range m.Oneofs {
		for _, v := range o.Variants {
			if v.NeedsBox {
				return true
			}
		}
	}
	return false
}

func writeTSMessage(g *protogen.GeneratedFile, m *DomainMessage, opts *Options) {
	if opts.TSTypesOnly {
		// Types-only mode: emit interface/type alias only, no Zod schemas.
		writeTSExplicitInterface(g, m, opts)
		return
	}

	if m.Comment != "" {
		g.P("/** ", sanitizeJSDoc(m.Comment), " */")
	}

	recursive := isRecursive(m)

	// Determine which oneofs need exclusivity refinement (2+ variants).
	var exclusiveOneofs []*DomainOneof
	for _, o := range m.Oneofs {
		if len(o.Variants) >= 2 {
			exclusiveOneofs = append(exclusiveOneofs, o)
		}
	}

	if recursive {
		// For recursive types: emit a manual type alias first, then use z.lazy().
		g.P("export type ", m.Name, " = {")
		for _, f := range m.Fields {
			if f.FieldSkip || f.IsOneof {
				continue
			}
			if f.Comment != "" {
				g.P("  /** ", sanitizeJSDoc(f.Comment), " */")
			}
			optMark := ""
			if tsFieldNeedsOptional(f, opts) || (recursive && !f.IsOneof && !tsFieldIsRequired(f, opts)) {
				optMark = "?"
			}
			g.P(fmt.Sprintf("  %s%s: %s;", f.CamelName, optMark, tsPlainType(f, opts)))
		}
		// Oneof variants in the type alias.
		for _, o := range m.Oneofs {
			for _, v := range o.Variants {
				tsType := tsPlainOneofVariantType(v, opts)
				g.P(fmt.Sprintf("  %s?: %s;", toCamelCase(v.ProtoName), tsType))
			}
		}
		g.P("};")
		// Note: z.lazy in Zod 3.x caches the schema after the first call, so no manual caching wrapper is needed here.
		g.P("export const ", m.Name, "Schema: z.ZodType<", m.Name, "> = /* @__PURE__ */ z.lazy(() => z.object({")
	} else {
		if opts.TSExplicitTypes {
			writeTSExplicitInterface(g, m, opts)
			g.P("export const ", m.Name, "Schema = /* @__PURE__ */ z.object({")
		} else {
			g.P("export const ", m.Name, "Schema = /* @__PURE__ */ z.object({")
		}
	}

	// Emit regular fields.
	for _, f := range m.Fields {
		if f.FieldSkip || f.IsOneof {
			continue
		}
		if f.Comment != "" || f.Deprecated {
			comment := sanitizeJSDoc(f.Comment)
			if f.Deprecated {
				if comment != "" {
					comment += " @deprecated"
				} else {
					comment = "@deprecated"
				}
			}
			g.P("  /** ", comment, " */")
		}
		zodExpr := tsFieldZodExpr(f, opts)
		g.P("  ", tsSafeKey(f.CamelName), ": ", zodExpr, ",")
	}

	// Oneof variants: emit each as an optional field.
	for _, o := range m.Oneofs {
		for _, v := range o.Variants {
			baseType := tsOneofVariantZodType(v, opts)
			if opts.ValidateEnabled() {
				baseType += tsOneofVariantZodConstraints(v, opts)
			}
			zodExpr := baseType + ".optional()"
			g.P("  ", toCamelCase(v.ProtoName), ": ", zodExpr, ",")
		}
	}

	strict := ""
	if opts.TSStrict {
		strict = ".strict()"
	}

	if recursive {
		if len(exclusiveOneofs) > 0 {
			// Chain .superRefine() inside the z.lazy() thunk.
			g.P("})" + strict + ".superRefine((data, ctx) => {")
			emitOneofExclusivity(g, exclusiveOneofs)
			g.P("}));")
		} else {
			g.P("})" + strict + ");")
		}
	} else if len(exclusiveOneofs) > 0 {
		// Chain .superRefine() to enforce mutual exclusion of oneof variants.
		g.P("})" + strict + ".superRefine((data, ctx) => {")
		emitOneofExclusivity(g, exclusiveOneofs)
		g.P("});")
	} else {
		g.P("})" + strict + ";")
	}

	if !recursive && !opts.TSExplicitTypes {
		g.P("export type ", m.Name, " = z.infer<typeof ", m.Name, "Schema>;")
	}
}

func emitOneofExclusivity(g *protogen.GeneratedFile, exclusiveOneofs []*DomainOneof) {
	for _, o := range exclusiveOneofs {
		varKeys := make([]string, 0, len(o.Variants))
		for _, v := range o.Variants {
			varKeys = append(varKeys, toCamelCase(v.ProtoName))
		}
		localVar := toCamelCase(o.FieldName)
		g.P(fmt.Sprintf("  const %sKeys = [%s] as const;",
			localVar, tsJoinQuoted(varKeys)))
		g.P(fmt.Sprintf("  let %sCount = 0;", localVar))
		g.P(fmt.Sprintf("  for (const k of %sKeys) {", localVar))
		g.P(fmt.Sprintf("    if ((data as Record<string, unknown>)[k] !== undefined) %sCount++;", localVar))
		g.P("  }")
		g.P(fmt.Sprintf("  if (%sCount > 1) {", localVar))
		g.P("    ctx.addIssue({")
		g.P("      code: z.ZodIssueCode.custom,")
		g.P(fmt.Sprintf(`      message: "at most one of " + %sKeys.join(", ") + " may be set",`,
			localVar))
		g.P(fmt.Sprintf("      path: [%sKeys.find(k => (data as Record<string, unknown>)[k] !== undefined) || %sKeys[0]],", localVar, localVar))
		g.P("    });")
		g.P("  }")
	}
}

// tsFieldZodExpr builds the complete Zod expression for a field,
// including base type, validation constraints, container wrapping, and optionality.
func tsFieldZodExpr(f *DomainField, opts *Options) string {
	baseType := tsZodType(f, opts)

	hasNullable := false
	if strings.HasSuffix(baseType, ".nullable()") {
		baseType = strings.TrimSuffix(baseType, ".nullable()")
		hasNullable = true
	}

	// Apply validation constraints to the base type.
	if opts.ValidateEnabled() {
		baseType += tsZodConstraints(f, opts)
	}

	if hasNullable {
		baseType += ".nullable()"
	}

	zodExpr := baseType

	if f.IsMap {
		// Map field: z.record(key, value).default({})
		valType := tsMapValueZodType(f.MapValue, opts)
		zodExpr = fmt.Sprintf("z.record(z.string().refine(k => k !== '__proto__' && k !== 'constructor' && k !== 'prototype'), %s)", valType)
		if opts.ValidateEnabled() {
			zodExpr += tsMapConstraints(f.ValidateConstraints)
		}
		zodExpr += ".default(() => ({}))"
	} else if f.Repeated {
		// Repeated field: z.array(base).default([])
		zodExpr = fmt.Sprintf("z.array(%s)", baseType)
		if opts.ValidateEnabled() {
			zodExpr += tsRepeatedConstraints(f.ValidateConstraints)
		}
		zodExpr += ".default(() => [])"
	} else {
		// Singular field: add .optional() or .nullish() if needed.
		if f.IsOneof || tsFieldIsRequired(f, opts) {
			// required or oneof — no default
		} else if f.Kind.IsWrapper() {
			// Wrapper types use .nullish() (undefined | null) instead of .nullable() or .optional().
			// At this point, .nullable() was stripped from the base type (line 293-295), constraints
			// were applied, then .nullable() was reattached (line 303-305). So HasSuffix is reliable.
			if strings.HasSuffix(zodExpr, ".nullable()") {
				zodExpr = strings.TrimSuffix(zodExpr, ".nullable()") + ".nullish()"
			} else {
				zodExpr += ".nullish()"
			}
		} else if tsFieldNeedsOptional(f, opts) {
			zodExpr += ".optional()"
		} else if f.Kind == FieldKindEnum && f.EnumDefaultName != "" {
			zodExpr += fmt.Sprintf(".default(%s)", strconv.Quote(f.EnumDefaultName))
		} else {
			zodExpr += ".default(" + tsScalarDefault(f.ScalarKind, opts) + ")"
		}
	}

	return zodExpr
}

// tsFieldNeedsOptional returns true when a singular field should be optional.
func tsFieldNeedsOptional(f *DomainField, opts *Options) bool {
	// Repeated and map fields use .default([]) / .default({}) instead.
	if f.Repeated || f.IsMap {
		return false
	}
	// Required fields (buf.validate) are never optional.
	if opts.ValidateEnabled() && f.ValidateConstraints != nil && f.ValidateConstraints.Required {
		return false
	}
	// All message-based types (messages, WKTs, wrappers) are optional in proto3.
	isMessageLike := f.Kind == FieldKindMessage || f.Kind == FieldKindTimestamp ||
		f.Kind == FieldKindDuration || f.Kind == FieldKindStruct ||
		f.Kind == FieldKindValue || f.Kind == FieldKindListValue ||
		f.Kind == FieldKindFieldMask || f.Kind == FieldKindEmpty ||
		f.Kind == FieldKindAny || f.Kind.IsWrapper()
	if isMessageLike || f.Optional || f.IsOneof {
		return true
	}
	if f.Kind == FieldKindEnum && f.EnumDefaultName == "" {
		return true
	}
	return false
}

func tsFieldIsRequired(f *DomainField, opts *Options) bool {
	return opts.ValidateEnabled() && f.ValidateConstraints != nil && f.ValidateConstraints.Required
}

// sanitizeJSDoc escapes JSDoc closing tags in comments.
func sanitizeJSDoc(s string) string {
	return strings.ReplaceAll(s, "*/", "* /")
}

// tsSafeKey wraps dangerous keys in computed property syntax.
func tsSafeKey(name string) string {
	if name == "__proto__" || name == "constructor" || name == "prototype" {
		return fmt.Sprintf("[%q]", name)
	}
	return name
}

// tsJoinQuoted returns a comma-separated list of double-quoted JS string literals.
// e.g. ["a", "b", "c"] → `"a", "b", "c"`.
func tsJoinQuoted(keys []string) string {
	quoted := make([]string, len(keys))
	for i, k := range keys {
		quoted[i] = strconv.Quote(k)
	}
	return strings.Join(quoted, ", ")
}

// tsScalarDefault returns the default value string for a scalar kind.
func tsScalarDefault(k protoreflect.Kind, opts *Options) string {
	switch k {
	case protoreflect.BoolKind:
		return "false"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind,
		protoreflect.Uint32Kind, protoreflect.Fixed32Kind,
		protoreflect.FloatKind, protoreflect.DoubleKind:
		return "0"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind,
		protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		if opts.TSInt64Style == "bigint" {
			return "0n"
		}
		return `"0"`
	case protoreflect.StringKind:
		return `""`
	case protoreflect.BytesKind:
		return `""`
	default:
		return `""`
	}
}

// tsOneofVariantZodType returns the Zod type expression for a oneof variant.
func tsOneofVariantZodType(v *OneofVariant, opts *Options) string {
	switch v.Kind {
	case FieldKindScalar:
		return tsScalarZodType(v.ScalarKind, opts)
	case FieldKindMessage:
		if v.NeedsBox {
			return fmt.Sprintf("z.lazy(() => %sSchema)", v.TypeName)
		}
		return fmt.Sprintf("%sSchema", v.TypeName)
	case FieldKindEnum:
		if opts.TSEnumStyle == "native" {
			return fmt.Sprintf("z.nativeEnum(%s)", v.TypeName)
		}
		return fmt.Sprintf("%sSchema", v.TypeName)
	case FieldKindTimestamp:
		return "z.string().datetime({ offset: true })"
	case FieldKindDuration:
		return `z.string().regex(new RegExp("^-?[0-9]+(\\.[0-9]+)?s$"), { message: "must be a valid Duration" })`
	case FieldKindStruct:
		return "z.record(z.string().refine(k => k !== '__proto__' && k !== 'constructor' && k !== 'prototype'), z.unknown())"
	case FieldKindValue:
		return "z.unknown()"
	case FieldKindListValue:
		return "z.array(z.unknown())"
	case FieldKindFieldMask:
		return `z.string().regex(new RegExp("^[a-zA-Z_][a-zA-Z0-9_]*(\\.[a-zA-Z_][a-zA-Z0-9_]*)*(,[a-zA-Z_][a-zA-Z0-9_]*(\\.[a-zA-Z_][a-zA-Z0-9_]*)*)*$"), { message: "must be a valid FieldMask (comma-separated field paths)" })`
	case FieldKindEmpty:
		return "z.record(z.string(), z.never())"
	case FieldKindAny:
		return `z.object({ "@type": z.string() }).passthrough()`
	default:
		if v.Kind.IsWrapper() {
			t, _ := tsWKTZodType(v.Kind, opts)
			return t
		}
		return "z.unknown()"
	}
}
